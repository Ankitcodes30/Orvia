  static Track _track({
    required String rawId,
    required String title,
    required String artist,
    required String album,
    required int durationSec,
    required String imageUrl,
  }) {
    final compositeId = '$pluginId::$rawId';
    return Track(
      id: compositeId,
      title: title,
      artists: [
        ArtistSummary(
          id: '',
          name: artist,
          thumbnail: Artwork(
            url: imageUrl,
            urlLow: imageUrl,
            urlHigh: imageUrl,
            layout: ImageLayout.square,
          ),
        ),
      ],
      album: AlbumSummary(
        id: '',
        title: album,
        artists: const [],
        thumbnail: Artwork(
          url: imageUrl,
          urlLow: imageUrl,
          urlHigh: imageUrl,
          layout: ImageLayout.square,
        ),
      ),
      durationMs: BigInt.from(durationSec * 1000),
      thumbnail: Artwork(
        url: imageUrl,
        urlLow: imageUrl,
        urlHigh: imageUrl,
        layout: ImageLayout.square,
      ),
      isExplicit: false,
    );
  }

  /// Returns curated tracks for a given artist name or ID if available.
  static List<Track>? getCuratedTracksForArtist(String artistName, {String? artistId}) {
    final cleanName = artistName.trim().toLowerCase();
    if (cleanName.contains('mohammed rafi') || artistId == '505312') {
      return getMohammedRafiTracks();
    }
    if (cleanName.contains('diljit dosanjh') || artistId == '468245') {
      return getDiljitDosanjhTracks();
    }
    if (cleanName == 'mukesh' || cleanName.contains('mukesh') || artistId == '455867') {
      return getMukeshTracks();
    }
    if (cleanName.contains('udit narayan') || artistId == '455127') {
      return getUditNarayanTracks();
    }
    if (cleanName.contains('asha bhosle') || artistId == '455166') {
      return getAshaBhosleTracks();
    }
    if (cleanName.contains('alka yagnik') || artistId == '455120') {
      return getAlkaYagnikTracks();
    }
    if (cleanName.contains('falguni pathak') || artistId == '467616') {
      return getFalguniPathakTracks();
    }
    return null;
  }

